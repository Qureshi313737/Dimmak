// Vital points ("Dim Mak" / kyusho) mapped to standard acupuncture points.
// Locations follow the WHO Standard Acupuncture Point Locations (2008), measured in
// "cun" (1 cun ≈ width of the person's own thumb at the knuckle).
//
// Marker placement: `ray` is cast at the skin; the first hit is where the marker sits.
//   F(x,y)  = from the front    B(x,y) = from the back    S(y,z) = from the person's left side
//   U(x,z)  = from above        R(o,d) = custom origin/direction   P(x,y,z) = fixed point
// Bilateral points are mirrored automatically.
const F = (x, y) => ({ o: [x, y, 2], d: [0, 0, -1] });
const B = (x, y) => ({ o: [x, y, -2], d: [0, 0, 1] });
const S = (y, z) => ({ o: [2, y, z], d: [-1, 0, 0] });
const U = (x, z) => ({ o: [x, 3, z], d: [0, -1, 0] });
const R = (o, d) => ({ o, d });
const P = (x, y, z) => ({ p: [x, y, z] });

